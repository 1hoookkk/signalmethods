function ax = fixedGrid(parent, position, aspect)
if nargin<3, aspect=3/2; end
ax=axes(parent,'Units','pixels','Position',position,'Color','w','XScale','log', ...
    'XLim',[20 20000],'YLim',[-30 30],'XTick',[100 1000 10000], ...
    'XTickLabel',{'100','1k','10k'},'YTick',[-30 0 30],'Box','on', ...
    'FontName','Arial','FontSize',9,'NextPlot','add','PlotBoxAspectRatio',[aspect 1 1], ...
    'XColor','k','YColor','k','PositionConstraint','innerposition');
for hz=[100 1000 10000], line(ax,[hz hz],[-30 30],'Color',[.84 .84 .84],'HitTest','off'); end
line(ax,[20 20000],[0 0],'Color',[.69 .69 .69],'HitTest','off');
end
